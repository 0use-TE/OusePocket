"""Generate a small LVGL bitmap font; firmware needs no TTF or runtime decoder.

Requires Pillow and fontTools only when regenerating; generated C is checked in.
The existing Noto subset is OFL-1.1; its rasterized derivative retains that license.
"""
from pathlib import Path
import hashlib
import re
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/fonts/NotoSansSC-Regular.subset.ttf'
DEST = ROOT / 'components/ouse_core/ouse_font_ui_16.c'
source = '\n'.join(p.read_text(encoding='utf-8') for p in [DEST.parent / 'ouse_core.c', DEST.parent / 'ouse_shell.c', ROOT / 'main/counter_app.c'])
letters = sorted(set(range(32, 127)) | {ord(c) for c in re.findall(r'[^\x00-\x7f]', source)})
font_data = TTFont(SOURCE)
missing = set(letters) - set(font_data.getBestCmap())
assert not missing, f'Missing source glyphs: {missing}'
font = ImageFont.truetype(str(SOURCE), 16)
bitmap = bytearray()
glyphs = ['    {0}, // reserved glyph 0']
for letter in letters:
    char = chr(letter)
    left, top, right, bottom = font.getbbox(char, anchor='ls')
    width, height = right-left, bottom-top
    image = Image.new('L', (max(1, width), max(1, height)))
    ImageDraw.Draw(image).text((-left, -top), char, font=font, fill=255, anchor='ls')
    values = [round(value * 15 / 255) for value in image.tobytes()] if width and height else []
    offset = len(bitmap)
    for i in range(0, len(values), 2):
        bitmap.append((values[i] << 4) | (values[i+1] if i+1 < len(values) else 0))
    glyphs.append(f'    {{.bitmap_index={offset}, .adv_w={round(font.getlength(char)*16)}, '
                  f'.box_w={width}, .box_h={height}, .ofs_x={left}, .ofs_y={-bottom}}}, // U+{letter:04X}')
lines = ['// SPDX-License-Identifier: OFL-1.1',
         '// Ouse UI bitmap subset derived from Noto Sans SC; see FONT-LICENSE.txt.',
         '// Generated by tools/generate-core-font.py; do not edit.',
         '// Source SHA256: ' + hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
         '#include "lvgl.h"', '', 'static const uint8_t bitmap[] = {']
lines += ['    '+','.join(f'0x{x:02x}' for x in bitmap[i:i+24])+',' for i in range(0, len(bitmap), 24)]
lines += ['};', 'static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {', *glyphs, '};',
          'static const uint16_t unicode[] = {',
          '    '+','.join(str(x-32) for x in letters), '};',
          'static const lv_font_fmt_txt_cmap_t cmaps[] = {{',
          f'    .range_start=32, .range_length={letters[-1]-32+1}, .glyph_id_start=1,',
          f'    .unicode_list=unicode, .list_length={len(letters)}, .type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY',
          '}};',
          'static const lv_font_fmt_txt_dsc_t font_data = {',
          '    .glyph_bitmap=bitmap, .glyph_dsc=glyphs, .cmaps=cmaps,',
          '    .cmap_num=1, .bpp=4, .bitmap_format=0',
          '};', 'const lv_font_t ouse_font_ui_16 = {',
          '    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,',
          '    .get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,',
          '    .line_height=22, .base_line=5, .subpx=LV_FONT_SUBPX_NONE,',
          '    .underline_position=-2, .underline_thickness=1, .dsc=&font_data',
          '};', '']
DEST.write_text('\n'.join(lines), encoding='utf-8')
print(f'Generated {len(letters)} glyphs, {len(bitmap)} bitmap bytes: {DEST.relative_to(ROOT)}')
