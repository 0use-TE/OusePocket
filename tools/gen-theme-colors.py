#!/usr/bin/env python3
"""Generate firmware palette include and VS Code preview theme copy from colors.json."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "components" / "ouse_core" / "theme" / "colors.json"
INC = ROOT / "components" / "ouse_core" / "theme" / "ouse_theme_palette.inc"
PREVIEW = ROOT / "tools" / "vscode-ouse-bpk" / "media" / "theme-colors.json"
EXTENSION_TS = ROOT / "tools" / "vscode-ouse-bpk" / "src" / "theme-colors.generated.ts"

TOKENS = [
    "background",
    "desktop",
    "surface",
    "text",
    "secondary",
    "accent",
    "button",
    "pressed",
    "icon",
    "border",
    "disabled",
    "error",
]


def parse_hex(value: str, path: str) -> int:
    if not isinstance(value, str) or not value.startswith("#") or len(value) != 7:
        raise SystemExit(f"{path}: expected #RRGGBB, got {value!r}")
    return int(value[1:], 16)


def load() -> dict:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    if data.get("api") != 1:
        raise SystemExit(f"{SOURCE}: api must be 1")
    declared = data.get("tokens")
    if declared != TOKENS:
        raise SystemExit(f"{SOURCE}: tokens must match {TOKENS}")
    for mode in ("light", "dark"):
        palette = data.get(mode)
        if not isinstance(palette, dict):
            raise SystemExit(f"{SOURCE}: missing {mode}")
        missing = [name for name in TOKENS if name not in palette]
        if missing:
            raise SystemExit(f"{SOURCE}: {mode} missing {missing}")
        extra = [name for name in palette if name not in TOKENS]
        if extra:
            raise SystemExit(f"{SOURCE}: {mode} unknown keys {extra}")
    return data


def write_inc(data: dict) -> None:
    lines = [
        "/* Generated by tools/gen-theme-colors.py — do not edit. */",
        "/* Source: components/ouse_core/theme/colors.json */",
        "static const ouse_theme_colors_t ouse_theme_palette_light = {",
    ]
    light = data["light"]
    dark = data["dark"]
    light_fields = ", ".join(f".{name}=0x{parse_hex(light[name], f'light.{name}'):06x}" for name in TOKENS)
    dark_fields = ", ".join(f".{name}=0x{parse_hex(dark[name], f'dark.{name}'):06x}" for name in TOKENS)
    lines.append(f"    {light_fields}")
    lines.append("};")
    lines.append("static const ouse_theme_colors_t ouse_theme_palette_dark = {")
    lines.append(f"    {dark_fields}")
    lines.append("};")
    lines.append("")
    INC.parent.mkdir(parents=True, exist_ok=True)
    INC.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def payload_of(data: dict) -> dict:
    return {
        "api": 1,
        "tokens": TOKENS,
        "light": {name: data["light"][name].lower() for name in TOKENS},
        "dark": {name: data["dark"][name].lower() for name in TOKENS},
    }


def write_preview(data: dict) -> None:
    PREVIEW.parent.mkdir(parents=True, exist_ok=True)
    PREVIEW.write_text(json.dumps(payload_of(data), indent=2) + "\n", encoding="utf-8", newline="\n")


def write_extension_ts(data: dict) -> None:
    body = json.dumps(payload_of(data), indent=2)
    lines = [
        "/* Generated by tools/gen-theme-colors.py — do not edit. */",
        "/* Source: components/ouse_core/theme/colors.json */",
        "export interface ThemeColorTable {",
        "  api: number;",
        "  tokens: string[];",
        "  light: Record<string, string>;",
        "  dark: Record<string, string>;",
        "}",
        "",
        f"export const BUNDLED_THEME_COLORS: ThemeColorTable = {body};",
        "",
    ]
    EXTENSION_TS.parent.mkdir(parents=True, exist_ok=True)
    EXTENSION_TS.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main() -> int:
    if not SOURCE.is_file():
        raise SystemExit(f"missing {SOURCE}")
    data = load()
    write_inc(data)
    write_preview(data)
    write_extension_ts(data)
    print(f"wrote {INC.relative_to(ROOT)}")
    print(f"wrote {PREVIEW.relative_to(ROOT)}")
    print(f"wrote {EXTENSION_TS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
